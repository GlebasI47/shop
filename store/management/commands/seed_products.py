class Command(BaseCommand):
    help = "Заполняет каталог демонстрационными категориями и товарами"

    def handle(self, *args, **options):
        new_categories = 0
        new_products = 0

        for category_name, products in CATALOG.items():
            category, category_created = Category.objects.get_or_create(name=category_name)
            if category_created:
                new_categories += 1

            for name, price, description in products:
                _, product_created = Product.objects.get_or_create(
                    name=name,
                    defaults={
                        "category": category,
                        "price": Decimal(price),
                        "description": description,
                    },
                )
                if product_created:
                    new_products += 1

        self.stdout.write(self.style.SUCCESS(
            f"Готово! Новых категорий: {new_categories}, новых товаров: {new_products}"
        ))
